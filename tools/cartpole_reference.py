"""Reference vectors for tessera/CartPole-v1.

Reimplements Gymnasium's CartPole-v1 step with the same operation order in
Python floats (IEEE binary64) and the platform libm, and writes:

- one-step vectors: a sampled state and action, the next state and the
  terminated flag;
- short trajectories: an initial state, replayed actions and every state.

Values are written as the hex bits of each binary64. The output is
committed at crates/tessera-rl-classic/tests/data/cartpole_reference.txt;
the Rust test compares within 4 ulps or 1e-12 relative (SPEC 18). This is
not the Gymnasium equivalence gate, which runs against the pinned
Gymnasium release in phase 1b. Gymnasium is not needed to run this script.

Usage: python3 tools/cartpole_reference.py > crates/tessera-rl-classic/tests/data/cartpole_reference.txt
"""

import math
import random
import struct

GRAVITY = 9.8
MASSCART = 1.0
MASSPOLE = 0.1
TOTAL_MASS = MASSPOLE + MASSCART
LENGTH = 0.5
POLEMASS_LENGTH = MASSPOLE * LENGTH
FORCE_MAG = 10.0
TAU = 0.02
THETA_THRESHOLD = 12 * 2 * math.pi / 360
X_THRESHOLD = 2.4

ONE_STEP = 1000
EPISODES = 20
EPISODE_STEPS = 50
SEED = 20261031


def step(state, action):
    x, x_dot, theta, theta_dot = state
    force = FORCE_MAG if action == 1 else -FORCE_MAG
    costheta = math.cos(theta)
    sintheta = math.sin(theta)
    temp = (force + POLEMASS_LENGTH * (theta_dot * theta_dot) * sintheta) / TOTAL_MASS
    thetaacc = (GRAVITY * sintheta - costheta * temp) / (
        LENGTH * (4.0 / 3.0 - MASSPOLE * (costheta * costheta) / TOTAL_MASS)
    )
    xacc = temp - POLEMASS_LENGTH * thetaacc * costheta / TOTAL_MASS
    x = x + TAU * x_dot
    x_dot = x_dot + TAU * xacc
    theta = theta + TAU * theta_dot
    theta_dot = theta_dot + TAU * thetaacc
    return (x, x_dot, theta, theta_dot)


def terminated(state):
    x, _, theta, _ = state
    return x < -X_THRESHOLD or x > X_THRESHOLD or theta < -THETA_THRESHOLD or theta > THETA_THRESHOLD


def bits(v):
    return "%016x" % struct.unpack("<Q", struct.pack("<d", v))[0]


def row(values):
    return " ".join(bits(v) for v in values)


def main():
    rng = random.Random(SEED)
    print("# SPDX-License-Identifier: MIT OR Apache-2.0")
    print("# tessera/CartPole-v1 reference vectors; generated by tools/cartpole_reference.py")
    for _ in range(ONE_STEP):
        state = (
            rng.uniform(-X_THRESHOLD, X_THRESHOLD),
            rng.uniform(-3.0, 3.0),
            rng.uniform(-THETA_THRESHOLD, THETA_THRESHOLD),
            rng.uniform(-3.5, 3.5),
        )
        action = rng.randrange(2)
        nxt = step(state, action)
        print("step %s %d %s %d" % (row(state), action, row(nxt), int(terminated(nxt))))
    for _ in range(EPISODES):
        state = tuple(rng.uniform(-0.05, 0.05) for _ in range(4))
        print("episode %s" % row(state))
        for _ in range(EPISODE_STEPS):
            action = rng.randrange(2)
            state = step(state, action)
            done = terminated(state)
            print("t %d %s %d" % (action, row(state), int(done)))
            if done:
                break

if __name__ == "__main__":
    main()
