//! Oracle for `tessera_rl_num::math` version 1, backed by `libm` 0.2.16.
//!
//! - `generate`: writes `crates/tessera-rl-num/src/math/vectors.rs` to
//!   stdout.
//! - `diff <seed> <count>`: compares every function against `libm` on
//!   `count` seeded pseudo-random inputs (uniform bit patterns and uniform
//!   values in `[-20, 20)`) and exits non-zero on any mismatch. NaN payloads
//!   are not compared (ADR-0008).

use std::io::{self, Write};
use std::process::ExitCode;

use tessera_rl_num::math;

type Unary = (&'static str, fn(f64) -> f64, fn(f64) -> f64);
type Binary = (&'static str, fn(f64, f64) -> f64, fn(f64, f64) -> f64);

const UNARY: [Unary; 7] = [
    ("sin", math::sin, libm::sin),
    ("cos", math::cos, libm::cos),
    ("tan", math::tan, libm::tan),
    ("atan", math::atan, libm::atan),
    ("exp", math::exp, libm::exp),
    ("ln", math::ln, libm::log),
    ("tanh", math::tanh, libm::tanh),
];

const BINARY: [Binary; 2] = [
    ("atan2", math::atan2, libm::atan2),
    ("hypot", math::hypot, libm::hypot),
];

const EDGES: [f64; 35] = [
    0.0,
    -0.0,
    f64::from_bits(1),
    -f64::from_bits(1),
    f64::from_bits(0x000f_ffff_ffff_ffff),
    f64::MIN_POSITIVE,
    -f64::MIN_POSITIVE,
    1e-300,
    1e-8,
    0.5,
    -0.5,
    1.0,
    -1.0,
    2.0,
    core::f64::consts::FRAC_PI_4,
    core::f64::consts::FRAC_PI_2,
    core::f64::consts::PI,
    -core::f64::consts::PI,
    3.0,
    10.0,
    100.0,
    709.78,
    709.79,
    -745.13,
    -745.14,
    1e6,
    1e22,
    1e300,
    f64::MAX,
    -f64::MAX,
    f64::INFINITY,
    f64::NEG_INFINITY,
    f64::NAN,
    // Large arguments that take the Payne-Hanek reduction path.
    f64::from_bits(0x7396_ac5b_262c_a1ff),
    f64::from_bits(0x4199_21fb_5444_2d18),
];

/// Marsaglia xorshift64; only used to pick test inputs.
fn xorshift(state: &mut u64) -> u64 {
    *state ^= *state << 13;
    *state ^= *state >> 7;
    *state ^= *state << 17;
    *state
}

#[expect(clippy::cast_precision_loss, reason = "53-bit integer, exact")]
fn uniform(state: &mut u64) -> f64 {
    ((xorshift(state) >> 11) as f64 / 9_007_199_254_740_992.0) * 40.0 - 20.0
}

fn same(a: f64, b: f64) -> bool {
    (a.is_nan() && b.is_nan()) || a.to_bits() == b.to_bits()
}

fn hex(v: f64) -> String {
    format!("0x{:016x}", v.to_bits())
}

fn generate(out: &mut impl Write) -> io::Result<()> {
    let mut inputs = EDGES.to_vec();
    let mut state = 42;
    inputs.extend((0..64).map(|_| uniform(&mut state)));
    let pairs: Vec<(f64, f64)> = inputs
        .iter()
        .copied()
        .zip(inputs.iter().rev().copied())
        .collect();

    writeln!(out, "// SPDX-License-Identifier: MIT OR Apache-2.0")?;
    writeln!(out)?;
    writeln!(out, "//! Reference vectors for math version 1.")?;
    writeln!(out)?;
    writeln!(
        out,
        "#![expect(clippy::unreadable_literal, reason = \"generated bit patterns\")]"
    )?;
    writeln!(out)?;
    writeln!(
        out,
        "// Generated by tools/math-oracle from libm 0.2.16 on {}-{}. Do not edit.",
        std::env::consts::ARCH,
        std::env::consts::OS
    )?;
    let list =
        |values: &mut dyn Iterator<Item = f64>| values.map(hex).collect::<Vec<_>>().join(", ");
    writeln!(
        out,
        "pub(super) const INPUTS: &[u64] = &[{}];",
        list(&mut inputs.iter().copied())
    )?;
    for (name, _, oracle) in UNARY {
        writeln!(
            out,
            "pub(super) const {}: &[u64] = &[{}];",
            name.to_uppercase(),
            list(&mut inputs.iter().map(|&x| oracle(x)))
        )?;
    }
    for (name, _, oracle) in BINARY {
        let rows: Vec<String> = pairs
            .iter()
            .map(|&(a, b)| format!("({}, {}, {})", hex(a), hex(b), hex(oracle(a, b))))
            .collect();
        writeln!(
            out,
            "pub(super) const {}: &[(u64, u64, u64)] = &[{}];",
            name.to_uppercase(),
            rows.join(", ")
        )?;
    }
    Ok(())
}

fn diff(out: &mut impl Write, seed: u64, count: u64) -> io::Result<u64> {
    let mut state = seed | 1;
    let mut mismatches = 0;
    for i in 0..count {
        // Alternate raw bit patterns (every exponent, subnormals, NaN) with
        // values in the common range.
        let draw = |state: &mut u64| {
            if i % 2 == 0 {
                f64::from_bits(xorshift(state))
            } else {
                uniform(state)
            }
        };
        let (x, y) = (draw(&mut state), draw(&mut state));
        for (name, ours, oracle) in UNARY {
            if !same(ours(x), oracle(x)) {
                mismatches += 1;
                writeln!(out, "{name}({}) differs", hex(x))?;
            }
        }
        for (name, ours, oracle) in BINARY {
            if !same(ours(x, y), oracle(x, y)) {
                mismatches += 1;
                writeln!(out, "{name}({}, {}) differs", hex(x), hex(y))?;
            }
        }
    }
    writeln!(
        out,
        "{count} inputs per function on {}-{}: {mismatches} mismatches",
        std::env::consts::ARCH,
        std::env::consts::OS
    )?;
    Ok(mismatches)
}

fn run() -> io::Result<bool> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let mut out = io::stdout().lock();
    match args
        .iter()
        .map(String::as_str)
        .collect::<Vec<_>>()
        .as_slice()
    {
        ["generate"] => generate(&mut out).map(|()| true),
        ["diff", seed, count] => match (seed.parse(), count.parse()) {
            (Ok(seed), Ok(count)) => diff(&mut out, seed, count).map(|m| m == 0),
            _ => usage(),
        },
        _ => usage(),
    }
}

fn usage() -> io::Result<bool> {
    writeln!(
        io::stderr(),
        "usage: tessera-rl-math-oracle generate | diff <seed> <count>"
    )?;
    Ok(false)
}

fn main() -> ExitCode {
    match run() {
        Ok(true) => ExitCode::SUCCESS,
        Ok(false) | Err(_) => ExitCode::FAILURE,
    }
}
