fn fixture(name: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures")
        .join(name)
}

fn sha256_hex(bytes: &[u8]) -> String {
    use sha2::Digest;
    use std::fmt::Write;
    sha2::Sha256::digest(bytes)
        .iter()
        .fold(String::new(), |mut s, b| {
            let _ = write!(s, "{b:02x}");
            s
        })
}

#[test]
fn test_onnx_fixtures_have_their_pinned_sha256() {
    for (name, sha) in FIXTURES {
        let bytes = std::fs::read(fixture(name)).unwrap();
        assert_eq!(sha256_hex(&bytes), sha, "{name}");
    }
}

/// Rule T: refuses unless telemetry is off and HOME is the scratch dir.
fn rule_t() -> (PathBuf, PathBuf) {
    assert_eq!(
        std::env::var(TELEMETRY_VARIABLE).as_deref(),
        Ok("1"),
        "refusing to load ONNX Runtime with telemetry enabled: set ORT_DISABLE_TELEMETRY=1"
    );
    let home = PathBuf::from(std::env::var_os("HOME").expect("HOME is set"));
    assert!(
        home.ends_with("target/onnx-test-home"),
        "HOME must be the scratch directory `make onnx-test` creates, got {}",
        home.display()
    );
    let lib = PathBuf::from(
        std::env::var_os("TESSERA_ONNXRUNTIME_LIB").expect("TESSERA_ONNXRUNTIME_LIB is set"),
    );
    (lib, home)
}

fn assert_no_telemetry(home: &Path) {
    for dir in [
        home.join(".cache/Microsoft/DeveloperTools/.onnxruntime"),
        home.join("Library/Application Support/Microsoft/DeveloperTools/.onnxruntime"),
    ] {
        assert!(
            !dir.exists(),
            "telemetry directory appeared: {}",
            dir.display()
        );
    }
}

fn evaluator(lib: &Path, model: &str) -> Result<OnnxEvaluator<Connect4>, OnnxError> {
    OnnxEvaluator::new(&Connect4Config {}, &fixture(model), &OnnxOptions::new(lib))
}

/// The constant model's outputs, written by Rust.
struct Canned;

impl Evaluator<Connect4> for Canned {
    fn evaluate(
        &mut self,
        _: &[Record<Connect4>],
        priors: &mut [f64],
        values: &mut [f64],
    ) -> Result<(), EvaluatorError> {
        priors.fill(1.0 / 7.0);
        values.fill(0.25);
        Ok(())
    }
}

fn search() -> Mcts<Connect4, Masked> {
    let mut p = EnvPool::<Connect4, Masked>::with_masks(
        Connect4Config {},
        PoolOptions::new(NonZeroU32::MIN, Seed::new(7)),
    )
    .unwrap();
    p.reset_all(Reseed::Keep).unwrap();
    let root = p.snapshot(0).unwrap();
    let o = SearchOptions::new(NonZeroU32::new(4096).unwrap(), NonZeroU32::new(8).unwrap());
    let pool = SearchPool::new(Connect4Config {}, o, &root, EnvPool::with_masks).unwrap();
    let mut cfg = PuctConfig::default();
    cfg.simulations = 200;
    Mcts::new(pool, cfg).unwrap()
}

fn visits(m: &Mcts<Connect4, Masked>) -> [u32; 7] {
    let mut out = [0u32; 7];
    m.root_visits(&mut out);
    out
}

/// The only cross-platform ONNX test: the constant model's outputs are
/// exactly the canned evaluator's, so the searches are bit-identical on
/// every platform.
#[test]
#[ignore = "opens the real ONNX Runtime: run through `make onnx-test`"]
fn test_onnx_constant_model_equals_canned_evaluator() {
    let (lib, home) = rule_t();
    let mut onnx = evaluator(&lib, "constant.onnx").unwrap();
    let (mut a, mut b) = (search(), search());
    for _ in 0..3 {
        a.run(&mut Canned).unwrap();
        b.run(&mut onnx).unwrap();
        assert_eq!(visits(&a), visits(&b));
        assert_eq!(a.select_action(0.0).unwrap(), b.select_action(0.0).unwrap());
    }
    assert!(visits(&a).iter().sum::<u32>() > 0);
    assert_no_telemetry(&home);
}

#[test]
#[ignore = "opens the real ONNX Runtime: run through `make onnx-test`"]
fn test_onnx_provenance_records_what_was_loaded() {
    let (lib, home) = rule_t();
    let onnx = evaluator(&lib, "constant.onnx").unwrap();
    let runtime = load_runtime(&lib, TelemetryPolicy::RequireDisabled).unwrap();
    let p = onnx.provenance();
    assert_eq!(p.model_sha256, FIXTURES[0].1);
    assert_eq!(p.library_sha256, sha256_hex(&std::fs::read(&lib).unwrap()));
    assert_eq!(p.library_sha256, runtime.sha256());
    assert_eq!(p.library_path, lib.canonicalize().unwrap());
    assert_eq!(p.library_version, PINNED_VERSION);
    assert_eq!(p.provider, CPU_PROVIDER);
    assert_eq!((p.intra_threads, p.inter_threads), (1, 1));
    assert_eq!(p.optimization_level, OPTIMIZATION_LEVEL);
    assert!(!p.telemetry_enabled);
    assert_eq!(p.arch, std::env::consts::ARCH);
    assert_no_telemetry(&home);
}

#[test]
#[ignore = "opens the real ONNX Runtime: run through `make onnx-test`"]
fn test_onnx_model_contract_refusals_are_typed() {
    let (lib, home) = rule_t();
    for model in ["wrong_input.onnx", "wrong_actions.onnx"] {
        let got = evaluator(&lib, model);
        assert!(
            matches!(got, Err(OnnxError::Contract { .. })),
            "{model}: {got:?}"
        );
    }
    assert_no_telemetry(&home);
}

#[test]
#[ignore = "opens the real ONNX Runtime: run through `make onnx-test`"]
fn test_onnx_model_trust_refusals_are_typed() {
    let (lib, home) = rule_t();
    // External data: the session is built from bytes, with no model
    // directory, so the external file is never resolved.
    let got = evaluator(&lib, "external.onnx");
    assert!(
        matches!(&got, Err(OnnxError::Model { reason, .. }) if reason.contains("external")),
        "{got:?}"
    );
    let mut small = OnnxOptions::new(&lib);
    small.max_model_bytes = 100;
    let got = OnnxEvaluator::<Connect4>::new(&Connect4Config {}, &fixture("constant.onnx"), &small);
    assert!(
        matches!(&got, Err(OnnxError::Model { reason, .. }) if reason.contains("cap")),
        "{got:?}"
    );
    let got = evaluator(&lib, "missing.onnx");
    assert!(matches!(got, Err(OnnxError::Model { .. })), "{got:?}");
    assert_no_telemetry(&home);
}

#[test]
#[ignore = "opens the real ONNX Runtime: run through `make onnx-test`"]
fn test_onnx_direct_evaluate_without_observations_fails() {
    let (lib, home) = rule_t();
    let mut onnx = evaluator(&lib, "constant.onnx").unwrap();
    let got = onnx.evaluate(&[], &mut [], &mut []);
    assert!(matches!(got, Err(EvaluatorError::Failed { .. })), "{got:?}");
    assert_no_telemetry(&home);
}
