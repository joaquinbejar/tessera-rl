//! The ONNX evaluator (ADR-0057) on Connect4.
//!
//! The fixture tests run by default and load nothing. Every test that opens
//! the real ONNX Runtime is ignored by default and runs through
//! `make onnx-test` (rule: no test loads ONNX Runtime with telemetry
//! enabled): it refuses to run unless `ORT_DISABLE_TELEMETRY=1` and `HOME`
//! is the scratch directory, and checks afterwards that no telemetry
//! directory appeared. All of them load the same library, so they share the
//! process's one runtime.

#![expect(
    clippy::unwrap_used,
    clippy::expect_used,
    reason = "test scenarios: a failure is the assertion"
)]

