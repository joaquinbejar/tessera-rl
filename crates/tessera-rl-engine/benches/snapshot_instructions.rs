//! Instruction counts of the engine's hot path and snapshot operations
//! (ADR-0025 PR gate, gungraun), on the counter test environment: one
//! Inline step, `snapshot_all` (copy only), `restore` and `fork` and
//! `fork_branched` (each including re-observation, ADR-0039). Setup runs
//! outside the measured region, and every benchmark returns its inputs so
//! that dropping them (and the allocator) is not counted either. Linux only (Valgrind); see `make gungraun`.

#![expect(clippy::unwrap_used, reason = "bench setup unwraps")]
#![expect(missing_docs, reason = "items generated by the gungraun macros")]

use core::num::NonZeroU32;
use std::hint::black_box;

use gungraun::{
    Callgrind, CallgrindMetrics, LibraryBenchmarkConfig, library_benchmark,
    library_benchmark_group, main,
};
use tessera_rl_engine::{ActionInput, EnvPool, PoolOptions, Record, Reseed};
use tessera_rl_num::identity::Seed;

#[path = "../tests/common/mod.rs"]
#[expect(dead_code, reason = "shared with the tests")]
mod common;

use common::{CountConfig, Counter};

const N: u32 = 1024;

type Pool = EnvPool<Counter>;

fn pool() -> Pool {
    let cfg = CountConfig {
        length: 1000,
        ..CountConfig::default()
    };
    let mut p = EnvPool::new(
        cfg,
        PoolOptions::new(NonZeroU32::new(N).unwrap(), Seed::new(1)),
    )
    .unwrap();
    p.reset_all(Reseed::Keep).unwrap();
    let actions = vec![0; p.outputs().rewards().len()];
    p.step(ActionInput {
        discrete: &actions,
        continuous: &[],
    })
    .unwrap();
    p
}

fn with_actions() -> (Pool, Vec<i32>) {
    let p = pool();
    let actions = vec![1; p.outputs().rewards().len()];
    (p, actions)
}

fn with_records() -> (Pool, Vec<Record<Counter>>) {
    let p = pool();
    let mut records = vec![p.snapshot(0).unwrap(); N as usize];
    p.snapshot_all(&mut records).unwrap();
    (p, records)
}

#[library_benchmark]
#[bench::n1024(setup = with_actions)]
fn step_inline((mut p, actions): (Pool, Vec<i32>)) -> (Pool, Vec<i32>) {
    let out = p
        .step(ActionInput {
            discrete: black_box(&actions),
            continuous: &[],
        })
        .unwrap();
    black_box(out.rewards().len());
    (p, actions)
}

#[library_benchmark]
#[bench::n1024(setup = with_records)]
fn snapshot_all_copy(
    (p, mut records): (Pool, Vec<Record<Counter>>),
) -> (Pool, Vec<Record<Counter>>) {
    p.snapshot_all(black_box(&mut records)).unwrap();
    (p, records)
}

#[library_benchmark]
#[bench::n1024(setup = with_records)]
fn restore_with_reobserve(
    (mut p, records): (Pool, Vec<Record<Counter>>),
) -> (Pool, Vec<Record<Counter>>) {
    for (id, record) in (0..N).zip(&records) {
        p.restore(id, black_box(record)).unwrap();
    }
    (p, records)
}

/// The pool and every destination but instance 0, allocated outside the
/// measured region (no allocator instructions in the counts).
fn with_destinations() -> (Pool, Vec<u32>) {
    (pool(), (1..N).collect())
}

#[library_benchmark]
#[bench::n1024(setup = with_destinations)]
fn fork_with_reobserve((mut p, dst): (Pool, Vec<u32>)) -> (Pool, Vec<u32>) {
    p.fork(0, black_box(&dst)).unwrap();
    (p, dst)
}

#[library_benchmark]
#[bench::n1024(setup = with_destinations)]
fn fork_branched_with_reobserve((mut p, dst): (Pool, Vec<u32>)) -> (Pool, Vec<u32>) {
    p.fork_branched(0, black_box(&dst), None).unwrap();
    (p, dst)
}

library_benchmark_group!(
    name = engine,
    benchmarks = [
        step_inline,
        snapshot_all_copy,
        restore_with_reobserve,
        fork_with_reobserve,
        fork_branched_with_reobserve
    ]
);

/// Callgrind with the cache simulation on (instruction counts and cache
/// misses, ADR-0025). The gate, a 2% limit on `Ir`, is passed by
/// `scripts/gungraun.sh`; the cache metrics are reported.
fn config() -> LibraryBenchmarkConfig {
    let mut config = LibraryBenchmarkConfig::default();
    config.tool(Callgrind::with_args(["--cache-sim=yes"]).format([CallgrindMetrics::All]));
    config
}

main!(config = config(), library_benchmark_groups = engine);
