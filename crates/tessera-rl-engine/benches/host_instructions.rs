//! Instruction counts of the host pool (ADR-0025 PR gate, gungraun;
//! ADR-0062, #272): Inline steps of `HostPool` over a host CartPole port.
//!
//! - `host_pool_steady`: 64 steps of 1,024 instances in steady state, the
//!   setup of `classic_instructions::cartpole_pool_steady` (300 settling
//!   steps of fixed xorshift actions, then 64 measured steps whose action
//!   rows are drawn in setup, resets mixed in);
//! - `host_pool_one`: the same at `num_envs = 1`, the per-call overhead.
//!
//! Setup runs outside the measured region, and every benchmark returns its
//! inputs so that dropping them is not counted. Linux only (Valgrind); see
//! `make gungraun`.

#![expect(clippy::unwrap_used, reason = "bench setup unwraps")]
#![expect(missing_docs, reason = "items generated by the gungraun macros")]

use core::num::NonZeroU32;
use std::hint::black_box;

use gungraun::{
    Callgrind, CallgrindMetrics, LibraryBenchmarkConfig, library_benchmark,
    library_benchmark_group, main,
};
use tessera_rl_classic::CartPoleConfig;
use tessera_rl_engine::{ActionInput, HostPool, PoolOptions, Reseed};
use tessera_rl_num::identity::Seed;

#[path = "support/host_cartpole.rs"]
mod host_cartpole;

use host_cartpole::HostCartPole;

type Pool = HostPool<HostCartPole, 1>;

/// Settling steps before the measurement, as `cartpole_pool_steady`.
const SETTLE_STEPS: usize = 300;

/// Measured steps, as `cartpole_pool_steady`.
const MEASURED_STEPS: usize = 64;

fn options(n: u32) -> PoolOptions {
    let mut o = PoolOptions::new(NonZeroU32::new(n).unwrap(), Seed::new(1));
    o.max_episode_steps = NonZeroU32::new(500);
    o
}

/// xorshift64: a fixed pseudo-random action stream, independent of the engine.
fn xorshift(s: &mut u64) -> u64 {
    *s ^= *s << 13;
    *s ^= *s >> 7;
    *s ^= *s << 17;
    *s
}

/// A host CartPole pool of `n` instances in steady state, and the next
/// `MEASURED_STEPS` batches of actions, all drawn here.
fn steady(n: u32) -> (Pool, Vec<Vec<i32>>) {
    let mut pool = Pool::new(&CartPoleConfig::default(), options(n)).unwrap();
    pool.reset_all(Reseed::Keep).unwrap();
    let mut seed = 0x9e37_79b9_7f4a_7c15_u64;
    let mut row = || -> Vec<i32> {
        (0..n)
            .map(|_| i32::from(xorshift(&mut seed) & 1 == 1))
            .collect()
    };
    for _ in 0..SETTLE_STEPS {
        let actions = row();
        pool.step(ActionInput {
            discrete: &actions,
            continuous: &[],
        })
        .unwrap();
    }
    let rows = (0..MEASURED_STEPS).map(|_| row()).collect();
    (pool, rows)
}

fn run((mut pool, rows): (Pool, Vec<Vec<i32>>)) -> (Pool, Vec<Vec<i32>>) {
    for actions in &rows {
        let out = pool
            .step(ActionInput {
                discrete: black_box(actions),
                continuous: &[],
            })
            .unwrap();
        black_box(out.rewards().first().copied());
    }
    (pool, rows)
}

#[library_benchmark]
#[bench::n1024(setup = steady, args = (1024))]
fn host_pool_steady(input: (Pool, Vec<Vec<i32>>)) -> (Pool, Vec<Vec<i32>>) {
    run(input)
}

#[library_benchmark]
#[bench::n1(setup = steady, args = (1))]
fn host_pool_one(input: (Pool, Vec<Vec<i32>>)) -> (Pool, Vec<Vec<i32>>) {
    run(input)
}

library_benchmark_group!(name = host, benchmarks = [host_pool_steady, host_pool_one]);

/// The glibc dispatch pin of every instruction-count run.
const GLIBC_TUNABLES: &str = include_str!("../../../benches/gungraun/GLIBC_TUNABLES");

/// The same Callgrind configuration as `snapshot_instructions`.
fn config() -> LibraryBenchmarkConfig {
    let mut config = LibraryBenchmarkConfig::default();
    config.env("GLIBC_TUNABLES", GLIBC_TUNABLES.trim());
    config.tool(
        Callgrind::with_args([
            "--cache-sim=yes",
            "--I1=32768,8,64",
            "--D1=32768,8,64",
            "--LL=8388608,16,64",
        ])
        .format([CallgrindMetrics::All]),
    );
    config
}

main!(config = config(), library_benchmark_groups = host);
