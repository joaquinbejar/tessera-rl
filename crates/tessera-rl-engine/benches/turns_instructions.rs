//! Instruction counts of masked and turn-based steps (ADR-0025 PR gate,
//! gungraun; P2-M1a): one Inline step of 1024 instances of
//!
//! - the counter environment with masks (`Masked`): the mask write in the
//!   observation pass, for a simultaneous environment;
//! - the race environment, `Sequential` with masks: the mask write, the
//!   acting update and the turn-order check (`check_turns`).
//!
//! Setup runs outside the measured region, and every benchmark returns its
//! inputs so that dropping them is not counted. Linux only (Valgrind); see
//! `make gungraun`.

#![expect(clippy::unwrap_used, reason = "bench setup unwraps")]
#![expect(missing_docs, reason = "items generated by the gungraun macros")]

use core::num::NonZeroU32;
use std::hint::black_box;

use gungraun::{
    Callgrind, CallgrindMetrics, LibraryBenchmarkConfig, library_benchmark,
    library_benchmark_group, main,
};
use tessera_rl_engine::{ActionInput, EnvPool, Masked, PoolOptions, Reseed};
use tessera_rl_num::identity::Seed;

#[path = "../tests/common/mod.rs"]
mod common;

#[path = "../tests/common/race.rs"]
mod race;

use common::{CountConfig, Counter};
use race::{RaceConfig, RaceEnv};

const N: u32 = 1024;

fn options() -> PoolOptions {
    PoolOptions::new(NonZeroU32::new(N).unwrap(), Seed::new(1))
}

fn masked_counter() -> (EnvPool<Counter, Masked>, Vec<i32>) {
    let cfg = CountConfig {
        length: 1000,
        ..CountConfig::default()
    };
    let mut p = EnvPool::with_masks(cfg, options()).unwrap();
    p.reset_all(Reseed::Keep).unwrap();
    let actions = vec![1; p.outputs().unwrap().rewards().len()];
    (p, actions)
}

fn sequential_race() -> (EnvPool<RaceEnv, Masked>, Vec<i32>) {
    let cfg = RaceConfig {
        target: 100,
        both_act: false,
    };
    let mut p = EnvPool::with_masks(cfg, options()).unwrap();
    p.reset_all(Reseed::Keep).unwrap();
    let actions = vec![1; p.outputs().unwrap().rewards().len()];
    (p, actions)
}

#[library_benchmark]
#[bench::n1024(setup = masked_counter)]
fn masked_step(
    (mut p, actions): (EnvPool<Counter, Masked>, Vec<i32>),
) -> (EnvPool<Counter, Masked>, Vec<i32>) {
    let out = p
        .step(ActionInput {
            discrete: black_box(&actions),
            continuous: &[],
        })
        .unwrap();
    black_box(out.masks().len());
    (p, actions)
}

#[library_benchmark]
#[bench::n1024(setup = sequential_race)]
fn sequential_step(
    (mut p, actions): (EnvPool<RaceEnv, Masked>, Vec<i32>),
) -> (EnvPool<RaceEnv, Masked>, Vec<i32>) {
    let out = p
        .step(ActionInput {
            discrete: black_box(&actions),
            continuous: &[],
        })
        .unwrap();
    black_box(out.acting().len());
    (p, actions)
}

library_benchmark_group!(name = turns, benchmarks = [masked_step, sequential_step]);

/// The glibc dispatch pin of every instruction-count run.
const GLIBC_TUNABLES: &str = include_str!("../../../benches/gungraun/GLIBC_TUNABLES");

/// The same Callgrind configuration as `snapshot_instructions`.
fn config() -> LibraryBenchmarkConfig {
    let mut config = LibraryBenchmarkConfig::default();
    config.env("GLIBC_TUNABLES", GLIBC_TUNABLES.trim());
    config.tool(
        Callgrind::with_args([
            "--cache-sim=yes",
            "--I1=32768,8,64",
            "--D1=32768,8,64",
            "--LL=8388608,16,64",
        ])
        .format([CallgrindMetrics::All]),
    );
    config
}

main!(config = config(), library_benchmark_groups = turns);
