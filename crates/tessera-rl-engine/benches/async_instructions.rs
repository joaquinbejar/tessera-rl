//! Instruction count of an Async round (issue #83, ADR-0047): the drain job's
//! work on the worker, part of the ADR-0025 gate. Linux only (Valgrind);
//! `make gungraun`.
//!
//! One round sends all 256 instances of the engine's counter environment and
//! receives them in batches of 64, on one worker with no spinning. Only the
//! drain job is counted (`run_drain`, collected inclusively): claims from the
//! submission ring, the chunk steps and the completion pushes. With one
//! worker, the send pushes every id before it publishes the job, so the
//! claims, and the count, do not depend on timing. The caller's side is not
//! counted: how often it polls depends on the scheduler, as in
//! `threaded_instructions`. The kernel (futex time, wake-ups) is invisible
//! here.

#![expect(clippy::unwrap_used, reason = "bench setup unwraps")]
#![expect(missing_docs, reason = "items generated by the gungraun macros")]

use gungraun::{
    Callgrind, EntryPoint, LibraryBenchmarkConfig, library_benchmark, library_benchmark_group, main,
};

#[path = "../tests/async_round/mod.rs"]
mod async_round;
#[path = "../tests/common/mod.rs"]
mod common;

use async_round::{Input, round_256};

// The body is `async_round::round`, which the `async_instructions_body`
// test also runs natively.
#[library_benchmark]
#[bench::round_256(setup = round_256)]
fn drain(input: Input) -> Input {
    async_round::round(input)
}

/// The glibc dispatch pin of every instruction-count run.
const GLIBC_TUNABLES: &str = include_str!("../../../benches/gungraun/GLIBC_TUNABLES");

library_benchmark_group!(
    name = async_mode;
    config = LibraryBenchmarkConfig::default().tool(
        // Threads are not separated: the gate (scripts/gungraun.sh) reads one
        // callgrind file per bench, and the drain runs on a worker thread.
        Callgrind::with_args(["--toggle-collect=*batch*run_drain*", "--separate-threads=no"])
            .entry_point(EntryPoint::None)
    );
    benchmarks = drain
);

fn config() -> LibraryBenchmarkConfig {
    let mut config = LibraryBenchmarkConfig::default();
    config.env("GLIBC_TUNABLES", GLIBC_TUNABLES.trim());
    config
}

main!(config = config(); library_benchmark_groups = async_mode);
