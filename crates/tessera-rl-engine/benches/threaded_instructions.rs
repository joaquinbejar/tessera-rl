//! Instruction counts of the threaded Sync step (issue #76), a report and not
//! part of the ADR-0025 gate. Linux only (Valgrind); `make gungraun-threaded`.
//!
//! Callgrind serializes threads, and how long a thread waits depends on its
//! scheduler, so a whole-process count is not a property of the code. Two
//! counts are stable instead, each over the same [`STEPS`] steps of 256
//! instances on 4 workers with no spinning:
//!
//! - `caller`: the calling thread inside the benchmark function: validation,
//!   publication, waiting and the outputs. Not the workers.
//! - `jobs`: every job body on every worker, collected inside the gang's
//!   `trampoline`: chunk claiming and the environment's work, setup's reset
//!   included. Not a worker's idle loop or its wake-up.
//!
//! Measured per thread (arm64, 16 steps): `caller` has all its count on the
//! calling thread and 0 on each worker; `jobs` has 0 on the calling thread and
//! about a quarter on each of the 4 workers.
//!
//! Neither counts the kernel: futex time, context switches and wake-up latency
//! are invisible here, and so are effects of code layout on real caches and
//! branch prediction, which is what wall-clock runs see.

#![expect(clippy::unwrap_used, reason = "bench setup unwraps")]
#![expect(missing_docs, reason = "items generated by the gungraun macros")]

use core::num::{NonZeroU32, NonZeroUsize};
use std::hint::black_box;

use gungraun::{
    Callgrind, EntryPoint, LibraryBenchmarkConfig, library_benchmark, library_benchmark_group, main,
};
use tessera_rl_engine::{ActionInput, EnvPool, PoolOptions, Reseed, SyncOptions, WaitBackend};
use tessera_rl_num::identity::Seed;

#[path = "../tests/common/mod.rs"]
mod common;

use common::{CountConfig, Counter};

const N: u32 = 256;
const STEPS: u32 = 16;

fn pool(wait: WaitBackend) -> (EnvPool<Counter>, Vec<i32>) {
    let options = PoolOptions {
        chunk_size: NonZeroU32::new(32).unwrap(),
        ..PoolOptions::new(NonZeroU32::new(N).unwrap(), Seed::new(1))
    };
    let cfg = CountConfig {
        length: 1000,
        ..CountConfig::default()
    };
    let sync = SyncOptions {
        spin: 0,
        wait,
        ..SyncOptions::new(NonZeroUsize::new(4).unwrap())
    };
    let mut p = EnvPool::new(cfg, options)
        .unwrap()
        .with_workers(sync)
        .unwrap();
    p.reset_all(Reseed::Keep).unwrap();
    let actions = vec![1; p.outputs().unwrap().rewards().len()];
    (p, actions)
}

fn park() -> (EnvPool<Counter>, Vec<i32>) {
    pool(WaitBackend::Park)
}

fn native() -> (EnvPool<Counter>, Vec<i32>) {
    pool(WaitBackend::Native)
}

fn steps((mut p, actions): (EnvPool<Counter>, Vec<i32>)) -> (EnvPool<Counter>, Vec<i32>) {
    for _ in 0..STEPS {
        p.step(ActionInput {
            discrete: black_box(&actions),
            continuous: &[],
        })
        .unwrap();
        black_box(p.outputs().unwrap().rewards());
    }
    (p, actions)
}

#[library_benchmark]
#[bench::park(setup = park)]
#[bench::native(setup = native)]
fn caller(input: (EnvPool<Counter>, Vec<i32>)) -> (EnvPool<Counter>, Vec<i32>) {
    steps(input)
}

#[library_benchmark]
#[bench::park(setup = park)]
#[bench::native(setup = native)]
fn jobs(input: (EnvPool<Counter>, Vec<i32>)) -> (EnvPool<Counter>, Vec<i32>) {
    steps(input)
}

/// The glibc dispatch pin of every instruction-count run.
const GLIBC_TUNABLES: &str = include_str!("../../../benches/gungraun/GLIBC_TUNABLES");

library_benchmark_group!(name = caller_side; benchmarks = caller);

library_benchmark_group!(
    name = job_bodies;
    config = LibraryBenchmarkConfig::default().tool(
        Callgrind::with_args(["--toggle-collect=*gang*trampoline*"]).entry_point(EntryPoint::None)
    );
    benchmarks = jobs
);

fn config() -> LibraryBenchmarkConfig {
    let mut config = LibraryBenchmarkConfig::default();
    config.env("GLIBC_TUNABLES", GLIBC_TUNABLES.trim());
    config
}

main!(config = config(); library_benchmark_groups = caller_side, job_bodies);
