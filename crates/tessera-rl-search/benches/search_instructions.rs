//! Instruction counts of search (ADR-0025 PR gate, gungraun) on Connect
//! Four: one batched expansion of the root's 7 children, and one PUCT
//! call of 256 simulations (selection, batched expansion, a uniform
//! evaluator, backup), from the empty board. Setup runs outside the
//! measured region, and the benchmarks return their inputs so that
//! dropping them is not counted either. Linux only (Valgrind); see `make
//! gungraun`.

#![expect(clippy::unwrap_used, reason = "bench setup unwraps")]
#![expect(missing_docs, reason = "items generated by the gungraun macros")]

use core::num::NonZeroU32;
use std::hint::black_box;

use gungraun::{
    Callgrind, CallgrindMetrics, LibraryBenchmarkConfig, library_benchmark,
    library_benchmark_group, main,
};
use tessera_rl_engine::{EnvPool, Masked, PoolOptions, Record, Reseed};
use tessera_rl_games::{Connect4, Connect4Config};
use tessera_rl_num::identity::Seed;
use tessera_rl_search::{
    Evaluator, EvaluatorError, Eviction, Mcts, NodeHandle, PuctConfig, SearchOptions, SearchPool,
};

/// Uniform priors and a zero value.
pub struct Uniform;

impl Evaluator<Connect4> for Uniform {
    fn evaluate(
        &mut self,
        _: &[Record<Connect4>],
        priors: &mut [f64],
        values: &mut [f64],
    ) -> Result<(), EvaluatorError> {
        priors.fill(1.0 / 7.0);
        values.fill(0.0);
        Ok(())
    }
}

fn pool(capacity: u32, batch: u32) -> SearchPool<Connect4, Masked> {
    let mut p = EnvPool::<Connect4, Masked>::with_masks(
        Connect4Config {},
        PoolOptions::new(NonZeroU32::MIN, Seed::new(1)),
    )
    .unwrap();
    p.reset_all(Reseed::Keep).unwrap();
    let mut o = SearchOptions::new(
        NonZeroU32::new(capacity).unwrap(),
        NonZeroU32::new(batch).unwrap(),
    );
    o.eviction = Eviction::Oldest;
    SearchPool::new(
        Connect4Config {},
        o,
        &p.snapshot(0).unwrap(),
        EnvPool::with_masks,
    )
    .unwrap()
}

type Expand = (
    SearchPool<Connect4, Masked>,
    Vec<(NodeHandle, u32)>,
    Vec<NodeHandle>,
);

/// A fresh pool and the 7 root requests.
fn root_requests(capacity: u32) -> Expand {
    let s = pool(capacity, 7);
    let r = s.root();
    (s, (0..7).map(|a| (r, a)).collect(), vec![r; 7])
}

/// A fresh search of 256 simulations.
fn search(simulations: u32) -> Mcts<Connect4, Masked> {
    let mut cfg = PuctConfig::default();
    cfg.simulations = simulations;
    Mcts::new(pool(1_024, 8), cfg).unwrap()
}

#[library_benchmark]
#[bench::n7(setup = root_requests, args = (64))]
fn expand_batch((mut s, requests, mut out): Expand) -> Expand {
    s.expand(black_box(&requests), &mut out).unwrap();
    (s, requests, out)
}

#[library_benchmark]
#[bench::sims_256(setup = search, args = (256))]
fn puct_run(mut m: Mcts<Connect4, Masked>) -> Mcts<Connect4, Masked> {
    m.run(&mut Uniform).unwrap();
    black_box(m.select_action(0.0).unwrap());
    m
}

library_benchmark_group!(name = search, benchmarks = [expand_batch, puct_run]);

/// The glibc dispatch pin of every instruction-count run.
const GLIBC_TUNABLES: &str = include_str!("../../../benches/gungraun/GLIBC_TUNABLES");

/// Callgrind with the cache simulation on (instruction counts and cache
/// misses, ADR-0025). The gate, a 2% limit on `Ir`, is passed by
/// `scripts/gungraun.sh`; the cache metrics are reported.
fn config() -> LibraryBenchmarkConfig {
    let mut config = LibraryBenchmarkConfig::default();
    // glibc picks memcpy and memset variants by CPU (ifunc), which would
    // make the counts depend on the machine: pin them to the baseline
    // variants (benches/gungraun/README.md).
    config.env("GLIBC_TUNABLES", GLIBC_TUNABLES.trim());
    config.tool(
        // A fixed cache geometry, so cache metrics compare across hosts.
        Callgrind::with_args([
            "--cache-sim=yes",
            "--I1=32768,8,64",
            "--D1=32768,8,64",
            "--LL=8388608,16,64",
        ])
        .format([CallgrindMetrics::All]),
    );
    config
}

main!(config = config(), library_benchmark_groups = search);
